def extract_sizes(cn_name: str) -> tuple[list[str], list[str]]:
    """抽取尺寸信息，返回 (厘米规格, 床宽规格)。"""
    cms: list[str] = []
    for m in _SIZES_CM.finditer(cn_name):
        parts = [p for p in m.groups() if p]
        cms.append("×".join(parts) + "cm")

    widths: list[str] = []
    for m in _WIDTH_M.finditer(_FEET.sub(" ", cn_name)):
        label = _BED_WIDTH.get(m.group(1))
        if label and label not in widths:
            widths.append(label)
    return cms, widths


def extract_specs(cn_name: str) -> list[str]:
    """抽取「床单款 / 床笠款」这类床品规格说明。"""
    return [ja for cn, ja in _SPEC_WORDS.items() if cn in cn_name]


def extract_set_pieces(cn_name: str) -> int | None:
    """从商品名推断套件件数。"""
    if "四件套" in cn_name:
        return 4
    if "三件套" in cn_name:
        return 3
    return None


# ---------------------------------------------------------------------------
# 术语消费 / 标题重组
# ---------------------------------------------------------------------------
def consume_terms(text: str, terms: list[str]) -> tuple[list[str], str]:
    """按最长优先「消费」术语，返回 (命中的日语术语, 剩余文本)。

    「消费」指命中后从工作串里删掉该词，这样 ``全棉双层纱`` 不会又被 ``全棉``
    重复翻译一次；顺序敏感是刻意的。
    """
    work = text
    found: list[str] = []
    for term in sorted(terms, key=len, reverse=True):
        if term in work:
            found.append(TERM_MAP[term])
            work = work.replace(term, " ")
    return found, work


def detect_materials(cn_name: str) -> list[str]:
    """识别素材关键词（日语）。"""
    found, _ = consume_terms(cn_name, MATERIAL_TERMS)
    return found


def detect_categories(cn_name: str) -> list[str]:
    """识别品类关键词（日语）。"""
    found, _ = consume_terms(cn_name, CATEGORY_TERMS)
    return found


def extract_pattern(cn_name: str) -> str:
    """抽取花型 / 系列名（通常是商品名末尾那串中文，如「摘星小兔」「冰花」）。

    这类名称是商家的设计命名，硬翻没有意义，保留原词更利于买家比对商品图。
    """
    work = strip_noise(cn_name)
    work = _FEET.sub(" ", work)
    work = _SIZES_CM.sub(" ", work)
    work = _WIDTH_M.sub(" ", work)
    _, work = consume_terms(work, MATERIAL_TERMS)
    _, work = consume_terms(work, CATEGORY_TERMS)
    _, work = consume_terms(work, SPEC_TERMS)
    work = re.sub(r"[（）()【】\[\]×*×\d]+", " ", work)
    # 花型常以空白或连字符分隔（如「碧晨春泥-强遮光」），两种都要拆
    tokens = [t.strip(" -－—–…·/・,，、。") for t in re.split(r"[\s\-－—–/、,，|・]+", work)]
    tokens = [t for t in tokens if len(t) >= 2 and not t.isascii()]
    return tokens[-1] if tokens else ""


def localize_name(cn_name: str) -> str:
    """逐词翻译版本（用于关键词匹配与排障，不作为面向买家的标题）。"""
    out = strip_noise(cn_name)
    for cn in sorted(TERM_MAP, key=len, reverse=True):
        if cn in out:
            out = out.replace(cn, TERM_MAP[cn])
    return re.sub(r"\s+", " ", out).strip(" -・/|")


def compose_title(cn_name: str) -> str:
    """重组面向买家的日语标题：素材 + 品类 + 尺寸。

    只使用**已识别的日语属性**，宁短不乱——日本买家看到中文原词会直接流失。
    """
    pieces_cn = extract_set_pieces(cn_name)
    materials = detect_materials(cn_name)
    categories = detect_categories(cn_name)
    sizes_cm, bed_sizes = extract_sizes(cn_name)

    parts: list[str] = []
    if materials:
        parts.append(materials[0])
    if categories:
        parts.append(categories[0])
    elif pieces_cn:
        parts.append(f"{pieces_cn}点セット")

    size_text = sizes_cm[0] if sizes_cm else (bed_sizes[0] if bed_sizes else "")
    title = " ".join(parts) or "寝具"
    if size_text:
        title = f"{title} {size_text}"
    return title.strip()


