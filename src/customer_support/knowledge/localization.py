def care_instructions(ja_title: str) -> list[str]:
    """根据标题里的素材关键词给出保养建议。"""
    for hint, key in _CARE_KEY_HINTS:
        if hint in ja_title:
            return CARE_BY_MATERIAL[key]
    return [
        "洗濯表示に従ってお手入れしてください。",
        "乾燥機のご使用は避け、陰干しをおすすめします。",
    ]


def material_pitch(ja_title: str) -> str:
    """根据标题里的关键词返回一段卖点描述；没有命中时返回空串。

    返回空串而不是通用兜底文案，是为了让调用方（``catalog``）有机会用
    「品类级兜底」顶上来——品类兜底比通用兜底对买家有用得多。
    """
    for hint, pitch in PITCH_BY_KEYWORD:
        if hint in ja_title:
            return pitch
    return ""
